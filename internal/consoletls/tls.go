// Package consoletls implements console agent TLS identity and trust handling.
package consoletls

import (
	"crypto"
	"crypto/ecdsa"
	"crypto/elliptic"
	"crypto/rand"
	"crypto/sha256"
	"crypto/tls"
	"crypto/x509"
	"crypto/x509/pkix"
	"encoding/hex"
	"encoding/pem"
	"fmt"
	"math/big"
	"net/http"
	"net/url"
	"os"
	"time"
)

type Authority struct {
	Certificate *x509.Certificate
	Signer      crypto.Signer
	PEM         []byte
}

func LoadAuthority(certificateFile, keyFile string) (*Authority, error) {
	pair, err := tls.LoadX509KeyPair(certificateFile, keyFile)
	if err != nil {
		return nil, fmt.Errorf("cannot load agent certificate authority")
	}
	cert, err := x509.ParseCertificate(pair.Certificate[0])
	if err != nil {
		return nil, err
	}
	signer, ok := pair.PrivateKey.(crypto.Signer)
	if !ok || !cert.IsCA || cert.KeyUsage&x509.KeyUsageCertSign == 0 || time.Now().Before(cert.NotBefore) || time.Until(cert.NotAfter) < time.Hour {
		return nil, fmt.Errorf("invalid or expired agent certificate authority")
	}
	data, err := os.ReadFile(certificateFile)
	if err != nil {
		return nil, err
	}
	return &Authority{Certificate: cert, Signer: signer, PEM: data}, nil
}

func NewKeyAndCSR() ([]byte, string, error) {
	key, err := ecdsa.GenerateKey(elliptic.P256(), rand.Reader)
	if err != nil {
		return nil, "", err
	}
	der, err := x509.MarshalPKCS8PrivateKey(key)
	if err != nil {
		return nil, "", err
	}
	csr, err := x509.CreateCertificateRequest(rand.Reader, &x509.CertificateRequest{}, key)
	if err != nil {
		return nil, "", err
	}
	return pem.EncodeToMemory(&pem.Block{Type: "PRIVATE KEY", Bytes: der}), string(pem.EncodeToMemory(&pem.Block{Type: "CERTIFICATE REQUEST", Bytes: csr})), nil
}

func CSRForKey(keyPEM []byte) (string, error) {
	block, _ := pem.Decode(keyPEM)
	if block == nil {
		return "", fmt.Errorf("invalid client key")
	}
	key, err := x509.ParsePKCS8PrivateKey(block.Bytes)
	if err != nil {
		return "", fmt.Errorf("invalid client key")
	}
	signer, ok := key.(crypto.Signer)
	if !ok {
		return "", fmt.Errorf("invalid client key")
	}
	der, err := x509.CreateCertificateRequest(rand.Reader, &x509.CertificateRequest{}, signer)
	if err != nil {
		return "", err
	}
	return string(pem.EncodeToMemory(&pem.Block{Type: "CERTIFICATE REQUEST", Bytes: der})), nil
}

func PublicKeyHash(key any) string {
	der, err := x509.MarshalPKIXPublicKey(key)
	if err != nil {
		return ""
	}
	sum := sha256.Sum256(der)
	return hex.EncodeToString(sum[:])
}

func (a *Authority) Sign(csrPEM, credentialID, clusterID string) (string, string, time.Time, error) {
	if len(csrPEM) > 16384 {
		return "", "", time.Time{}, fmt.Errorf("CSR too large")
	}
	block, _ := pem.Decode([]byte(csrPEM))
	if block == nil {
		return "", "", time.Time{}, fmt.Errorf("invalid CSR")
	}
	csr, err := x509.ParseCertificateRequest(block.Bytes)
	if err != nil || csr.CheckSignature() != nil {
		return "", "", time.Time{}, fmt.Errorf("invalid CSR signature")
	}
	// Only the algorithm generated by the enrollment client is accepted.
	key, ok := csr.PublicKey.(*ecdsa.PublicKey)
	if !ok || key.Curve != elliptic.P256() {
		return "", "", time.Time{}, fmt.Errorf("CSR requires ECDSA P-256")
	}
	serial, err := rand.Int(rand.Reader, new(big.Int).Lsh(big.NewInt(1), 128))
	if err != nil {
		return "", "", time.Time{}, err
	}
	expires := time.Now().UTC().Add(24 * time.Hour)
	if expires.After(a.Certificate.NotAfter) {
		expires = a.Certificate.NotAfter
	}
	if time.Until(expires) < time.Hour {
		return "", "", time.Time{}, fmt.Errorf("agent certificate authority expires soon")
	}
	identity, _ := url.Parse("spiffe://optipod/cluster/" + url.PathEscape(clusterID) + "/credential/" + url.PathEscape(credentialID))
	template := &x509.Certificate{SerialNumber: serial, Subject: pkix.Name{CommonName: credentialID, OrganizationalUnit: []string{clusterID}}, URIs: []*url.URL{identity}, NotBefore: time.Now().Add(-time.Minute), NotAfter: expires, KeyUsage: x509.KeyUsageDigitalSignature, ExtKeyUsage: []x509.ExtKeyUsage{x509.ExtKeyUsageClientAuth}, BasicConstraintsValid: true}
	der, err := x509.CreateCertificate(rand.Reader, template, a.Certificate, csr.PublicKey, a.Signer)
	if err != nil {
		return "", "", time.Time{}, err
	}
	return string(pem.EncodeToMemory(&pem.Block{Type: "CERTIFICATE", Bytes: der})), PublicKeyHash(csr.PublicKey), expires, nil
}

func Client(caPEM, certificatePEM, keyPEM []byte) (*http.Client, error) {
	roots, err := x509.SystemCertPool()
	if err != nil {
		roots = x509.NewCertPool()
	}
	if len(caPEM) > 0 && !roots.AppendCertsFromPEM(caPEM) {
		return nil, fmt.Errorf("invalid console trust CA")
	}
	config := &tls.Config{MinVersion: tls.VersionTLS12, RootCAs: roots}
	if len(certificatePEM) > 0 || len(keyPEM) > 0 {
		pair, err := tls.X509KeyPair(certificatePEM, keyPEM)
		if err != nil {
			return nil, fmt.Errorf("invalid client certificate/key")
		}
		config.Certificates = []tls.Certificate{pair}
	}
	transport := http.DefaultTransport.(*http.Transport).Clone()
	transport.TLSClientConfig = config
	return &http.Client{Transport: transport, Timeout: 30 * time.Second, CheckRedirect: func(_ *http.Request, _ []*http.Request) error { return http.ErrUseLastResponse }}, nil
}

type Identity struct {
	CredentialID string    `json:"credentialID"`
	Token        string    `json:"token"`
	Certificate  string    `json:"certificate"`
	PrivateKey   string    `json:"privateKey"`
	CAPEM        string    `json:"caPEM"`
	ExpiresAt    time.Time `json:"expiresAt"`
}

func (i Identity) Client() (*http.Client, error) {
	return Client([]byte(i.CAPEM), []byte(i.Certificate), []byte(i.PrivateKey))
}
