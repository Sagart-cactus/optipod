'use strict';
const {chromium} = require('playwright');
const fs = require('node:fs/promises');
const assert = require('node:assert/strict');
const path = require('node:path');
let phase = 'launch';
(async () => {
  const fixture = JSON.parse(await fs.readFile(process.env.OPTIPOD_UI_FIXTURE, 'utf8'));
  const browser = await chromium.launch({headless:true});
  const context = await browser.newContext({acceptDownloads:true, viewport:{width:1280,height:950}});
  const page = await context.newPage(); const errors=[];
  page.on('pageerror', () => errors.push('JavaScript runtime error'));
  page.on('dialog', dialog => dialog.accept());
  const click = id => page.locator('#'+id).click();
  const fill = (form,name,value) => page.locator(`#${form} [name="${name}"]`).fill(value);
  const waitMessage = text => page.locator('#onboardingstatus').filter({hasText:text}).waitFor();
  try {
    phase='protected bootstrap';
    await page.goto(fixture.url); await click('openbootstrap');
    await fill('bootstrapform','bootstrap',fixture.bootstrap);
    await fill('bootstrapform','subject','browser-admin');
    await fill('bootstrapform','token',fixture.admin);
    await page.locator('#bootstrapform button').click();
    await click('manageclusters'); await waitMessage('Saved cluster settings');
    phase='wizard registration';
    await click('addcluster');
    for(const [name,value] of Object.entries({id:'browser-qa',name:'Browser QA',environment:'QA',kubeUID:fixture.uid})) await fill('registrationform',name,value);
    await click('wizardnext');
    await fill('registrationform','namespaces','app');
    await page.locator('#registrationform [name="metricsSource"]').selectOption('prometheus');
    await fill('registrationform','prometheusURL','http://prometheus.monitoring.svc:9090');
    await click('wizardnext');await click('saveregistration');await waitMessage('Registration saved');
    assert.match(await page.locator('#installcommands').innerText(),/optipod-console preflight/);
    phase='enrollment download';
    const enrollmentDownload=page.waitForEvent('download');await click('wizardissue');
    const enrollmentFile=await(await enrollmentDownload).path();
    const enrollment=JSON.parse(await fs.readFile(enrollmentFile,'utf8'));
    assert.equal(enrollment.clusterID,'browser-qa');assert.ok(enrollment.token.length>=32);
    assert.equal(enrollment.registration.metricsSource,'prometheus');
    assert.ok(!(await page.locator('body').innerText()).includes(enrollment.token));
    phase='resume after reload';
    await page.reload();await click('manageclusters');await waitMessage('Saved cluster settings');
    await page.locator('#registrations button').filter({hasText:'Resume setup'}).click();
    await click('editregistration');
    assert.equal(await page.locator('#registrationform [name="name"]').inputValue(),'Browser QA');
    await click('wizardnext');
    assert.equal(await page.locator('#registrationform [name="prometheusURL"]').inputValue(),'http://prometheus.monitoring.svc:9090');
    await click('wizardnext');await click('saveregistration');await waitMessage('Registration saved');
    phase='first Recommend policy';
    await click('verifycluster');await page.locator('#verifystep').waitFor();
    await fill('policyform','labelValue','checkout');
    const policyDownload=page.waitForEvent('download');await page.locator('#policyform button').click();
    const policy=await fs.readFile(await(await policyDownload).path(),'utf8');
    assert.match(policy,/mode: Recommend/);assert.match(policy,/minimumHistory: 1h/);assert.ok(!policy.includes('mode: Auto'));
    phase='environment template and bulk registration';
    await click('closewizard');
    await page.getByText('Environment templates and bulk onboarding',{exact:true}).click();
    await fill('templateform','name','qa-default');await page.locator('#templateform button').click();await waitMessage('Environment template saved');
    const bulk=[{id:'browser-prod',name:'Browser Production',environment:'production',kubeUID:fixture.peerUID,namespaces:['app'],metricsSource:'metrics-server',installMode:'new',installMethod:'gitops'}];
    await fill('bulkform','registrations',JSON.stringify(bulk));await page.locator('#bulkform button').click();await waitMessage('Batch registered');
    assert.equal(await page.locator('#registrations .onboardingrow').count(),2);
    phase='viewer grants and role enforcement';
    await page.getByText('Users and SSO group access',{exact:true}).click();
    await fill('grantform','subject','browser-viewer');await fill('grantform','clusters','browser-qa');await fill('grantform','namespaces','app');
    await page.locator('#grantform [name="issueToken"]').check();
    const viewerDownload=page.waitForEvent('download');await page.locator('#grantform button').click();
    const viewer=await fs.readFile(await(await viewerDownload).path(),'utf8');await waitMessage('Access saved');
    phase='disconnect, reconnect and notifications';
    const row=page.locator('#registrations .onboardingrow').filter({hasText:'Browser QA'});
    await row.getByRole('button',{name:'Disconnect',exact:true}).click();await waitMessage('Telemetry disconnected');
    await row.getByRole('button',{name:'Reconnect',exact:true}).click();await waitMessage('Reconnected');
    await page.getByText('Onboarding notifications',{exact:true}).click();
    const note=page.locator('#notifications button').first();await note.click();
    await page.getByText('Fleet health and recovery evidence',{exact:true}).click();
    assert.match(await page.locator('#fleethealth').innerText(),/No verified restore recorded/);
    if(process.env.OPTIPOD_UI_SCREENSHOT) await page.screenshot({path:process.env.OPTIPOD_UI_SCREENSHOT,fullPage:true});
    await click('closeonboarding');await click('logout');
    await page.locator('#token').fill(viewer);await page.locator('#loginform button').click();await page.locator('#console').waitFor();
    assert.equal(await page.locator('#manageclusters').isVisible(),false);
    const response=await context.request.get(fixture.url+'/api/admin/clusters');assert.equal(response.status(),403);
    phase='mobile sign-in layout';
    await click('logout');await page.locator('#login').waitFor();await page.setViewportSize({width:390,height:844});
    assert.ok(await page.locator('#loginform button').isVisible());
    phase='JavaScript runtime checks';assert.equal(errors.length,0);
    console.log('PASS: protected bootstrap, resumable wizard, enrollment download, Recommend policy, templates, bulk, grants, lifecycle, notifications, health and viewer denial');
  } finally {await browser.close();}
})().catch(error => {console.error(`FAIL: browser onboarding phase: ${phase} (${error.name}); details omitted to protect ephemeral credentials`);process.exitCode=1;});
